def _build_time_norms_table() -> str:
    """Формирует моноширинную таблицу нормативов времени (Приложение А).

    Колонка значений выравнивается точками программно — по самой длинной
    строке-описанию, а не вручную на глаз.
    """
    rows = [
        ("Вода, вино", "2–3 мин"),
        ("Напитки", "5–7 мин"),
        ("Салаты, закуски, супы", "5–10 мин"),
        ("Горячее", "10–20 мин"),
        ("Десерты", "5–7 мин"),
        ("Комфортное ожидание первого курса", "до 12 мин"),
        ("Разрыв между 1-м и 2-м курсом", "до 5 мин"),
        ("Блюдо на раздаче", "до 20 сек"),
        ("Грязная посуда на столе", "до 1 мин"),
        ("Запрос обратной связи", "в течение 2 мин после подачи"),
        ("Расчёт", "до 3 мин"),
        ("Подойти к рассчитавшимся гостям", "через 20 мин"),
        ("Ответ на звонок", "до 3-го гудка"),
    ]
    label_col = max(len(label) for label, _ in rows) + 1
    lines = []
    for label, value in rows:
        dots = "." * (label_col - len(label) + 2)
        lines.append(f"{label} {dots} {value}")
    return "<pre>" + "\n".join(lines) + "</pre>"


