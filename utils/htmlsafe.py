"""Экранирование обычного текста для безопасной вставки в сообщения
с parse_mode=HTML (например, коротких заголовков — названий пунктов,
групп, категорий, позиций)."""


def esc(text: str) -> str:
    """Экранирует &, < и > так, чтобы `text` отобразился в Telegram как
    есть, а не был воспринят как HTML-разметка. Порядок важен: сначала &
    (чтобы не задвоить уже вставленный &amp;), затем < и >. Кавычки не
    экранируются — Telegram HTML их не требует. None/пустая строка ->
    ''."""
    if not text:
        return ""
    return text.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")
